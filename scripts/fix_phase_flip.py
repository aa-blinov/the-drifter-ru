def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()

    with io.open(CORPUS, encoding="utf-8", newline="") as fh:
        corpus = list(csv.reader(fh))[1:]
    english = {"%s|%s" % (r[0], r[1]): r[4] for r in corpus}

    with io.open(TRANSLATION, encoding="utf-8-sig", newline="") as fh:
        table = list(csv.reader(fh))
    head = table[0]
    en_col = head.index("English")
    ru_col = head.index("Русский")

    changed = {}
    for row in table[1:]:
        if len(row) <= max(en_col, ru_col):
            continue
        source = row[en_col]
        if not re.search(r"phase-flip|phase flip|phaseflip", source, re.I):
            continue
        text = row[ru_col]
        new = text
        for whole, replacement in EXACT.items():
            if whole in new:
                new = new.replace(whole, replacement)
        for phrase in ORDER:
            if phrase in new:
                new = new.replace(phrase, VERB.get(phrase) or NOUN[phrase])
        if new != text:
            key = "%s|%s" % (row[0], row[1])
            changed[key] = new
            print("%-14s %s" % (key, new[:86]))

    print("lines changed: %d" % len(changed))

    if args.apply:
        for row in table[1:]:
            key = "%s|%s" % (row[0], row[1])
            if key in changed:
                row[ru_col] = changed[key]
        out = io.StringIO()
        csv.writer(out, lineterminator="\r\n").writerows(table)
        with io.open(TRANSLATION, "w", encoding="utf-8-sig", newline="") as fh:
            fh.write(out.getvalue())
        with io.open(MANUAL, encoding="utf-8") as fh:
            fixes = json.load(fh)
        fixes.update(changed)
        with io.open(MANUAL, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(fixes, fh, ensure_ascii=False, indent=2, sort_keys=True)
            fh.write("\n")
        glossary = json.load(io.open(GLOSSARY, encoding="utf-8"))
        glossary["phase-flip"] = "фазовый переворот"
        glossary["phase-flipping"] = "фазовый переворот"
        ordered = dict(sorted(glossary.items(), key=lambda kv: kv[0].lower()))
        with io.open(GLOSSARY, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(ordered, fh, ensure_ascii=False, indent=2, sort_keys=True)
            fh.write("\n")
        print("applied: %d lines, glossary %d entries"
              % (len(changed), len(glossary)))


if __name__ == "__main__":
    main()
